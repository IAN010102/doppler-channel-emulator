function a = ex1_steering(N, d_over_lambda, theta_deg)
% EX1_STEERING  第 1 關：導向向量 a(θ)  (steering vector)
%
% 先自己寫 → 卡住了再看下面的「提示」→ 最後才看 matlab/solutions/ex1_steering_solution.m
%
% 【這一關要做什麼】
%   一排 N 根天線排成一直線。聲音(電波)從角度 θ 的方向傳來，會「先到某幾根、後到另外幾根」，
%   所以每根天線收到的訊號，相位(波的進度)都不一樣。
%   導向向量 a(θ) 就是把「每根天線的相位」排成一個 N×1 的複數向量。
%   這個向量是 MVDR 的「指南針」：它告訴波束成形器，要把耳朵朝哪個方向聽。
%
% 【生活比喻】
%   一排同學站成一行聽演講。講者站在斜前方，離他最近的同學最早聽到，
%   最遠的最晚聽到。「每個人晚多少」的清單，就是導向向量。
%
% 【輸入輸出】
%   輸入  N              天線數量（例如 8）
%         d_over_lambda  天線間距，單位是波長（例如 0.5 代表半個波長）
%         theta_deg      來波方向，單位是「度」（0 度是正前方，正的往一邊偏）
%   輸出  a              N×1 的複數欄向量（第 1 個元素是第 0 根天線，相位為 0）
%
% 【對應數學式】
%       a_n(θ) = exp( -j · 2π · n · (d/λ) · sin θ ),   n = 0, 1, ..., N-1
%   符號：  n      第 n 根天線的編號（從 0 開始！第 0 根是參考點）
%           d/λ    天線間距除以波長（d_over_lambda）
%           θ      來波方向（要先把「度」換成「弧度」再放進 sin）
%           j      虛數單位（MATLAB 裡寫 1i）
%
% 【提示】（卡住了再往下看，一次只看一條）
%   提示 1：先做出 n = 0:N-1 這個列向量，再用 (:) 或 .' 轉成 N×1 的欄向量。
%   提示 2：MATLAB 的 sin 吃的是「弧度」。度換弧度：theta_deg * pi / 180（或 deg2rad）。
%   提示 3：整個式子可以一行寫完：exp(-1i * 2*pi * n * d_over_lambda * sin(theta_rad))。
%   提示 4：檢查：a(1) 一定等於 1（第 0 根天線沒有延遲）；每個元素的絕對值都等於 1。

a = nan(N, 1);                      % 還沒寫時的暫代值（NaN）

