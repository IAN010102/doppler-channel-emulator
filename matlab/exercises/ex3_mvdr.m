function w = ex3_mvdr(R, a)
% EX3_MVDR  第 3 關：MVDR 波束成形權重  (minimum variance distortionless response)
%
% 先自己寫 → 卡住了再看下面的「提示」→ 最後才看 matlab/solutions/ex3_mvdr_solution.m
%
% 【這一關要做什麼】
%   MVDR 要找一組權重 w（每根天線一個數字），把天線收到的訊號加權加起來，
%   同時做到兩件事：
%     (1) 目標方向 a 的訊號「原封不動」通過（w 與 a 的內積 = 1）；
%     (2) 其他方向（尤其是干擾）的總能量「越小越好」。
%   結果是一個會自動在干擾方向挖洞（零陷）的波束。公式很短，但這是整個課程的重點。
%
% 【生活比喻】
%   一個會戴降噪耳機的人：他先固定「好朋友講話的方向」音量不變，
%   再把耳機調到「其他所有聲音加起來最小」。吵鬧源在哪裡，耳機就把那裡的聲音壓得最低。
%
% 【輸入輸出】
%   輸入  R   N×N 樣本協方差（第 2 關的結果；這一關使用網頁給的 R，與第 2 關分開批改）
%         a   N×1 導向向量（你要聽的方向，第 1 關的結果）
%   輸出  w   N×1 權重向量，並且滿足  w' * a = 1
%
% 【對應數學式】
%       w = R⁻¹ a / ( aᴴ R⁻¹ a )
%   符號：  R⁻¹   R 的反矩陣（MATLAB 建議用 R \ a，不要真的算 inv(R)）
%           aᴴ    a 的共軛轉置（MATLAB 寫 a'）
%           分母   一個純量，作用是把結果「縮放」到 w' * a = 1
%
% 【提示】（卡住了再往下看，一次只看一條）
%   提示 1：先算 x = R \ a;   這就是 R⁻¹a。（反斜線 \ 比 inv(R)*a 更準、更快）
%   提示 2：分母 = a' * x（一個數字）。
%   提示 3：w = x / (a' * x)。
%   提示 4：檢查：w' * a 應該等於 1（誤差在 1e-12 左右）。
%   提示 5：快照數 L 小於天線數 N 時，R 沒有反矩陣，這一關不用處理（check_my_work 會跳過）。

w = nan(size(a));                   % 還沒寫時的暫代值（NaN）

%%% TODO 從這裡開始寫（約 2 行）
% x = ...;                          % x = R⁻¹ a
% w = ...;                          % 除以 aᴴ R⁻¹ a，讓 w' * a = 1
%%% TODO 到這裡為止

if any(isnan(w))
    disp('這一關還沒寫（ex3_mvdr）：請在 %%% TODO 區填入程式，存檔後再執行 check_my_work。');
end
end
