% 【這一關要做什麼】
%   權重 w 好不好，要用成績來看：波束輸出裡「想要的訊號」比「干擾 + 雜訊」強多少倍？
%   這個比值叫 SINR，通常用 dB（分貝）表示。數字越大越好。
%
% 【生活比喻】
%   在吵鬧的餐廳戴著耳機聊天：你聽到朋友的聲音有多大，除以「隔壁桌的吵鬧 + 空調的嘶嘶聲」
%   有多大。這個「清楚程度」換成分貝，就是 SINR。
%
% 【輸入輸出】
%   輸入  w       N×1 權重向量
%         h       N×1 真實的目標通道向量（目標訊號到每根天線的樣子，網頁給的）
%         aJ      N×1 干擾源的導向向量，「已經乘上干擾源的振幅 sqrt(P_j)」（網頁給的）
%         sigma2  每根天線的雜訊功率 σ²（一個正數）
%   輸出  sinr_dB 一個純量，單位 dB
%
% 【對應數學式】
%       SINR = |wᴴ h|²  /  ( |wᴴ a_J|²  +  σ² · ‖w‖² )
%       SINR_dB = 10 · log10( SINR )
%   符號：  wᴴh        權重對「目標」的輸出（複數，要取絕對值再平方才是功率）
%           wᴴ a_J     權重對「干擾」的輸出
%           σ²‖w‖²    雜訊經過權重後的功率（‖w‖² = w' * w 的實部）
%
% 【提示】（卡住了再往下看，一次只看一條）
%   提示 1：訊號功率 = abs(w' * h)^2。注意 w' 是共軛轉置，不要寫成 w.'。
%   提示 2：干擾功率 = abs(w' * aJ)^2。
%   提示 3：雜訊功率 = sigma2 * norm(w)^2（norm(w)^2 就是 w 的每個元素絕對值平方的和）。
%   提示 4：SINR = 訊號 / (干擾 + 雜訊)。
%   提示 5：換成 dB：功率比要用 10*log10(...)，不是 20*log10（20 是用在振幅比）。

