function sinr_dB = ex4_sinr(w, h, aJ, sigma2)
% EX4_SINR  第 4 關：輸出 SINR (dB)  (signal-to-interference-plus-noise ratio)
%
% 先自己寫 → 卡住了再看下面的「提示」→ 最後才看 matlab/solutions/ex4_sinr_solution.m
