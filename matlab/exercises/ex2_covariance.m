function R = ex2_covariance(X)
% EX2_COVARIANCE  第 2 關：樣本協方差矩陣 R̂  (sample covariance)
%
% 先自己寫 → 卡住了再看下面的「提示」→ 最後才看 matlab/solutions/ex2_covariance_solution.m
%
% 【這一關要做什麼】
%   天線陣列在 L 個時間點各收一次，每次收到 N 個數字（每根天線一個）。
%   把這 L 次「N 個數字」排成 N×L 的表格 X。
%   樣本協方差 R̂ 回答的問題是：「天線 m 和天線 n 收到的東西有多相像？」
%   它是 N×N 的矩陣，MVDR 要靠它知道「干擾從哪個方向來」。
%
% 【生活比喻】
%   N 個同學各自在 L 天記錄今天吵不吵。把「兩個人同一天都很吵」的次數平均起來，
%   就知道哪些人的耳朵被同一個噪音源影響——這張「同步程度表」就是協方差。
%
% 【輸入輸出】
%   輸入  X   N×L 複數矩陣；第 l 欄是第 l 次快照（snapshot），第 m 列是第 m 根天線
%   輸出  R   N×N 複數矩陣（Hermitian：R 等於它自己的共軛轉置）
%
% 【對應數學式】
%       R̂ = (1/L) · Σ_{l=1..L}  x_l · x_lᴴ  =  (1/L) · X · Xᴴ
%   符號：  x_l   X 的第 l 欄（第 l 次快照，N×1）
%           ᴴ     共軛轉置（MATLAB 的單引號 '  就是共軛轉置！）
%           L     快照數（X 的欄數）
%
% 【提示】（卡住了再往下看，一次只看一條）
%   提示 1：先用 [N, L] = size(X); 取出天線數與快照數。
%   提示 2：把 L 次「x·xᴴ」加起來，等價於一次矩陣乘法 X * X'。
%   提示 3：別忘了除以 L（這是「平均」，不是「總和」）。
%   提示 4：MATLAB 裡 X' 是共軛轉置，X.' 才是「不共軛」的轉置——這裡要用 X'。
%   提示 5：檢查：R 應該是 N×N，而且 R 等於 R'（Hermitian）；對角線都是正的實數。

R = nan(size(X, 1));                % 還沒寫時的暫代值（NaN）

